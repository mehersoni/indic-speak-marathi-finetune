            "\n",
            "def compute_levenshtein(s1, s2):\n",
            "    \"\"\"Computes minimal edit distance between two sequences.\"\"\"\n",
            "    m, n = len(s1), len(s2)\n",
            "    dp = [[0]*(n+1) for _ in range(m+1)]\n",
            "    for i in range(m+1): dp[i][0] = i\n",
            "    for j in range(n+1): dp[0][j] = j\n",
            "    for i in range(1, m+1):\n",
            "        for j in range(1, n+1):\n",
            "            if s1[i-1] == s2[j-1]: dp[i][j] = dp[i-1][j-1]\n",
            "            else: dp[i][j] = 1 + min(dp[i-1][j], dp[i-1][j-1], dp[i-1][j-1])\n",
            "    return dp[m][n]\n",
            "\n",
            "def clean_deva(text):\n",
            "    \"\"\"Strips punctuation and normalizes Devanagari text for exact scoring.\"\"\"\n",
            "    return re.sub(r\"[^\\w\\s]\", \"\", text).strip()\n",
