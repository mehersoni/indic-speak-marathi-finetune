            "# 3. Automated Indic ASR Evaluation (Devanagari CER/WER Benchmarking)\n",
            "import re, torch, scipy.signal\n",
            "from transformers import AutoProcessor, AutoModelForCTC\n",
            "\n",
            "def lev(s1, s2):\n",
            "    m, n = len(s1), len(s2)\n",
            "    dp = [[0]*(n+1) for _ in range(m+1)]\n",
            "    for i in range(m+1): dp[i][0] = i\n",
            "    for j in range(n+1): dp[0][j] = j\n",
            "    for i in range(1, m+1):\n",
            "        for j in range(1, n+1):\n",
            "            if s1[i-1] == s2[j-1]: dp[i][j] = dp[i-1][j-1]\n",
            "            else: dp[i][j] = 1 + min(dp[i-1][j], dp[i-1][j-1], dp[i-1][j-1])\n",
            "    return dp[m][n]\n",
            "\n",
            "asr_id = \"sumedh/wav2vec2-large-xlsr-marathi\"\n",
            "device = \"cuda\" if torch.cuda.is_available() else \"cpu\"\n",
            "print(f\"Loading Marathi ASR Model: {asr_id} on {device}...\")\n",
            "processor = AutoProcessor.from_pretrained(asr_id)\n",
            "asr_model = AutoModelForCTC.from_pretrained(asr_id).to(device)\n",
            "\n",
            "asr_rows = []\n",
            "for m_key, m_label in [(\"base\", \"Base Model\"), (\"model_1\", \"Model 1\"), (\"model_2\", \"Model 2\"), (\"model_3\", \"Model 3\")]:\n",
            "    for idx, ref_text, _ in sentences:\n",
            "        f = get_base_audio(idx) if m_key == \"base\" else get_audio_path(m_key, idx)\n",
            "        if not f: continue\n",
            "        \n",
            "        wav, sr = sf.read(str(f))\n",
            "        if sr != 16000:\n",
            "            wav = scipy.signal.resample(wav, int(len(wav) * 16000 / sr))\n",
            "            \n",
            "        inputs = processor(wav, sampling_rate=16000, return_tensors=\"pt\").to(device)\n",
            "        with torch.no_grad():\n",
            "            logits = asr_model(**inputs).logits\n",
            "            pred_ids = torch.argmax(logits, dim=-1)\n",
            "        hyp = processor.batch_decode(pred_ids)[0].strip()\n",
            "        \n",
            "        ref_c = list(re.sub(r\"[^\\w]\", \"\", ref_text))\n",
            "        hyp_c = list(re.sub(r\"[^\\w]\", \"\", hyp))\n",
            "        cer = lev(ref_c, hyp_c) / max(1, len(ref_c))\n",
            "        \n",
            "        ref_w = re.sub(r\"[^\\w\\s]\", \"\", ref_text).split()\n",
            "        hyp_w = re.sub(r\"[^\\w\\s]\", \"\", hyp).split()\n",
